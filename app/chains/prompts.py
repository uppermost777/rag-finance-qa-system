"""Prompt 模板集中管理（中文）。

- ``REWRITE_PROMPT``：多轮对话的查询改写（把「那它和定投比呢」补全为完整问题）
- ``RAG_PROMPT``   ：基于检索上下文作答（强约束 + 引用编号 + 兜底话术 + 风险提示）
- ``GUARD_PROMPT`` ：辅助判断问题是否属于投资建议 / 荐股类敏感请求（规则之外的可选二次校验）
"""

from __future__ import annotations

from langchain_core.prompts import ChatPromptTemplate

from app.guard.compliance import DISCLAIMER

# --------------------------------------------------------------------------- 查询改写
REWRITE_SYSTEM = (
    "你是检索查询改写助手，服务于一个面向大学生的理财知识问答系统。\n"
    "任务：结合多轮对话历史，把用户的最新问题改写成一句完整、可独立检索的中文问句。\n"
    "要求：\n"
    "1. 补全省略的主语、宾语与指代（例如「那它和定投比呢」→「货币基金和基金定投有什么区别」）；\n"
    "2. 保留原问题中的数字、期限与专有名词，不得变更；\n"
    "3. 只输出改写后的问句本身，不要解释、不要加引号、不要输出多余内容；\n"
    "4. 若最新问题本身已完整，则原样输出。"
)

REWRITE_PROMPT = ChatPromptTemplate.from_messages(
    [
        ("system", REWRITE_SYSTEM),
        ("human", "对话历史：\n{history}\n\n用户最新问题：{question}\n\n改写后的问句："),
    ]
)

# --------------------------------------------------------------------------- RAG 生成
RAG_SYSTEM = (
    "你是「大学生理财知识问答系统」的答疑助手。请严格遵守以下规则：\n"
    "1. 只依据【参考资料】回答，不要使用资料之外的任何记忆或推测；\n"
    "2. 参考资料中没有的内容，必须明确回答「知识库中未收录」，不得编造；\n"
    "3. 引用资料时用 [1][2] 这样的编号标注在对应句子的末尾，编号必须与参考资料编号一致；\n"
    "4. 语言面向在校大学生，通俗易懂，先给结论再解释，正文不超过 400 字；\n"
    "5. 不推荐任何具体的基金、股票或理财产品，不预测涨跌，不承诺收益；\n"
    "6. 回答末尾固定追加风险提示：{disclaimer}"
)

RAG_PROMPT = ChatPromptTemplate.from_messages(
    [
        ("system", RAG_SYSTEM),
        (
            "human",
            "【参考资料】\n{context}\n\n【用户问题】{question}\n\n请依据上述参考资料作答：",
        ),
    ]
).partial(disclaimer=DISCLAIMER)

# --------------------------------------------------------------------------- 合规辅助判断
GUARD_SYSTEM = (
    "你是金融合规审核助手，负责判断用户问题是否属于「投资建议 / 荐股荐基 / 承诺收益」类敏感请求。\n"
    "判断标准：索要具体买卖标的、具体买卖时点、收益承诺，或要求对某产品作投资价值背书 → 敏感；\n"
    "对概念、制度、计算方法的询问（如「什么是基金定投」「存款保险保多少」）→ 不敏感。\n"
    '只输出一个 JSON：{"sensitive": true/false, "reason": "不超过 30 字的理由"}'
)

GUARD_PROMPT = ChatPromptTemplate.from_messages(
    [("system", GUARD_SYSTEM), ("human", "用户问题：{question}")]
)

# 检索为空 / 候选全部低于阈值时的兜底话术
NO_CONTEXT_ANSWER = (
    "知识库中未收录与这个问题直接相关的内容。你可以换一种问法，"
    "或先在「知识库管理」中上传相关资料后再试。"
    + DISCLAIMER
)
